fn build() -> Vec<JobDetail> {
    let now = Utc::now();
    SEEDS
        .iter()
        .enumerate()
        .map(|(i, s)| {
            let co = &COMPANIES[s.company];
            let id = format!("job_{:03}", i + 1);
            let posted_at = now - Duration::hours(s.hours_ago);
            let open_days = s.hours_ago / DAY;

            let fit = s.score.map(|score| Match {
                score,
                label: match score {
                    80.. => MatchLabel::Strong,
                    65..=79 => MatchLabel::Good,
                    50..=64 => MatchLabel::Fair,
                    _ => MatchLabel::Low,
                },
                reasons: s.reasons.iter().map(|r| r.to_string()).collect(),
            });
            let has_match = fit.is_some();

            let skills: Vec<String> = s.skills.iter().map(|k| k.to_string()).collect();
            let matched = skills
                .iter()
                .filter(|k| !s.missing.contains(&k.as_str()))
                .cloned()
                .collect();

            JobDetail {
                job: JobSummary {
                    id: id.clone(),
                    title: s.title.to_owned(),
                    company: Company {
                        name: co.name.to_owned(),
                        domain: co.domain.to_owned(),
                        industries: co.industries.iter().map(|x| x.to_string()).collect(),
                        description: co.description.to_owned(),
                    },
                    locations: s.locations.iter().map(|x| x.to_string()).collect(),
                    workplace: s.workplace,
                    employment_type: s.employment,
                    seniority: s.seniority,
                    department: s.department.to_owned(),
                    salary: s.salary.map(|(min, max, period)| Salary {
                        min,
                        max,
                        currency: "USD".to_owned(),
                        period,
                    }),
                    posted_at,
                    first_seen_at: posted_at + Duration::minutes(20),
                    repost_count: s.reposts,
                    possibly_stale: open_days > 60 || s.reposts > 2,
                    source: s.source,
                    apply_url: format!("https://{}/careers/{id}", co.domain),
                    fit,
                },
                summary: s.summary.to_owned(),
                description_html: description(s, co),
                skills,
                yoe_min: s.yoe,
                education: s.education.map(str::to_owned),
                workplace_note: s.note.map(str::to_owned),
                breakdown: has_match.then_some(MatchBreakdown {
                    experience: s.breakdown.0,
                    skill: s.breakdown.1,
                    education: s.breakdown.2,
                }),
                keywords: has_match.then(|| KeywordGap {
                    matched,
                    missing: s.missing.iter().map(|x| x.to_string()).collect(),
                }),
            }
        })
        .collect()
}

fn description(s: &Seed, co: &Co) -> String {
    let skills: String = s
        .skills
        .iter()
        .map(|k| format!("<li>Experience with {k}</li>"))
        .collect();
    let yoe = match s.yoe {
        Some(0) | None => "No prior professional experience required.".to_owned(),
        Some(y) => format!("{y}+ years of relevant experience."),
    };
    let education = s
        .education
        .map(|e| format!("<li>{e}</li>"))
        .unwrap_or_default();
    format!(
        "<h3>About {name}</h3><p>{about}</p>\
         <h3>The role</h3><p>{summary}</p>\
         <h3>What you'll do</h3><ul>\
         <li>Design, build and ship features with a small, collaborative team</li>\
         <li>Review code and help keep quality high</li>\
         <li>Work with product and design to decide what to build next</li></ul>\
         <h3>What we're looking for</h3><ul><li>{yoe}</li>{education}{skills}</ul>\
         <h3>Benefits</h3><ul><li>Health, dental and vision coverage</li>\
         <li>401(k) with company match</li><li>Learning budget</li></ul>",
        name = co.name,
        about = co.description,
        summary = s.summary,
    )
}
